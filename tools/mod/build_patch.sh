#!/bin/bash
# Patch edition of the Callo mod: a kit of patches for the ORIGINAL game files, to apply to a
# finished disc image after other mods (Zenith, the randomizer) with tools/mod/patch_image.py.
# Run from the repo root inside WSL. Output: build/mod/kit.
#
#   src/BATTLE/BATTLE.PRG/mod/callo.c -> ENDING/CALLO.BIN, a new file inside the padding before
#       ENDING/NULL.DAT, loaded at MOD_BASE by stub.c, which goes in INITBTL.PRG's spare tail.
#   src/BATTLE/BATTLE.PRG/mod/menu.c  -> ENDING/CALLOMNU.BIN, loaded by the mod when menus need it.
#   BATTLE.PRG, MENU3.PRG, MENU0.PRG: calls redirected to the mod (tools/mod/build_mod.py), same
#       size. MENUF.PRG: rebuilt with SELECTABLE_ROULETTE (Zenith doesn't touch it).
#
# Addresses come from a SHIFTCHECK build of BATTLE.PRG (its layout is the original's, with every
# symbol, statics included); the patched files are copies of the originals in data/.
set -euo pipefail

OUT=build/mod
MODDIR=build/src/BATTLE/BATTLE.PRG/mod
SYMS=build/data/BATTLE/BATTLE.PRG.strict.elf
INITBTL_VRAM=0x800F9800
MOD_BASE=0x800F6400     # above Zenith's variables (it uses RAM up to 0x800F60B0)
MOD_LIMIT=0x800F9800    # INITBTL.PRG / effect overlays load here
MOD_LBA=303280          # inside the padding between ENDING.XA (ends 303264) and NULL.DAT
MOD_MAGIC=0x4F4C4143    # "CALO"
MENU_BASE=0x80109800    # callo.h MENU_MODULE
MENU_LIMIT=0x8010C000   # the heap
MENU_LBA=$((MOD_LBA + 8))  # callo.h MENU_MODULE_LBA
MENU_MAGIC=0x554E4D43   # "CMNU"

rm -rf "$OUT/kit" "$OUT/original" "$OUT/patched" "$OUT/maxstats"
mkdir -p "$OUT/original" "$OUT/patched"

# The selectable roulette: MENUF.PRG in the original layout
make -j8 SELECTABLE_ROULETTE=1 build/data/MENU/MENUF.PRG
cp build/data/MENU/MENUF.PRG "$OUT/patched/"

# Symbols, and the mod compiled for the patch edition (no VS_CALLO)
make -j8 SHIFTCHECK=1 build/data/BATTLE/BATTLE.PRG "$MODDIR/callo.c.o" "$MODDIR/menu.c.o"

addr() { mipsel-linux-gnu-nm "$1" | awk -v s="$2" '$3 == s {print "0x" $1; exit}'; }

# 1. The mod (header with its entry point, see build_mod.py pack)
tools/mod/link_module.sh "$MODDIR/callo.c.o" $((MOD_BASE + 0x20)) "$SYMS" "$OUT/callo.elf" "$OUT/callo.bin"
ENTRY=$(addr "$OUT/callo.elf" vs_mod_spawnCallo)
python3 tools/mod/build_mod.py pack "$OUT/callo.bin" "$OUT/CALLO.BIN" \
    $MOD_MAGIC $MOD_BASE $MOD_LIMIT "$(addr "$OUT/callo.elf" mod_checked_end)" "$ENTRY"
MOD_SIZE=$(stat -c %s "$OUT/CALLO.BIN")
if (( MOD_SIZE > (MENU_LBA - MOD_LBA) * 2048 )); then echo "CALLO.BIN overlaps CALLOMNU.BIN on disc"; exit 1; fi

# 2. The menu module, linked against the game and the mod
tools/mod/link_module.sh "$MODDIR/menu.c.o" $((MENU_BASE + 0x20)) "$SYMS:$OUT/callo.elf" \
    "$OUT/menu.elf" "$OUT/menu.bin"
m() { addr "$OUT/menu.elf" "$1"; }
python3 tools/mod/build_mod.py pack "$OUT/menu.bin" "$OUT/CALLOMNU.BIN" \
    $MENU_MAGIC $MENU_BASE $MENU_LIMIT "$(m mod_checked_end)" \
    "$(m vs_menu_equipEnter)" "$(m vs_menu_equipLeave)" "$(m vs_menu_equipCallo)" \
    "$(m vs_menu_markSpells)" "$(m vs_menu_toggleSpell)"

# 3. The loader, after INITBTL.PRG (16-aligned)
{
    echo "/* Generated by tools/mod/build_patch.sh */"
    echo "#define MOD_BASE  $MOD_BASE"
    echo "#define MOD_ENTRY $ENTRY"
    echo "#define MOD_MAGIC $MOD_MAGIC"
    echo "#define MOD_LBA   $MOD_LBA"
    echo "#define MOD_SIZE  $MOD_SIZE"
} > "$OUT/mod_config.h"
rm -f "$MODDIR/stub.c.o"
make -j8 SHIFTCHECK=1 "$MODDIR/stub.c.o"
INITBTL_SIZE=$(stat -c %s data/BATTLE/INITBTL.PRG)
LOADER_BASE=$(printf '0x%X' $(( (INITBTL_VRAM + INITBTL_SIZE + 15) & ~15 )))
tools/mod/link_module.sh "$MODDIR/stub.c.o" "$LOADER_BASE" "$SYMS" "$OUT/loader.elf" "$OUT/loader.bin"

# 4. Patches, on copies of the original files
for f in BATTLE/BATTLE.PRG BATTLE/INITBTL.PRG MENU/MENU3.PRG MENU/MENU0.PRG MENU/MENUF.PRG; do
    cp "data/$f" "$OUT/original/"
done
cp data/BATTLE/BATTLE.PRG data/BATTLE/INITBTL.PRG data/MENU/MENU3.PRG data/MENU/MENU0.PRG "$OUT/patched/"
c() { addr "$OUT/callo.elf" "$1"; }
s() { addr "$SYMS" "$1"; }
INITBTL_LOAD=$(awk '/define VS_INITBTL_PRG_SIZE/ {print $3}' build/src/include/lbas.h)
python3 tools/mod/build_mod.py initbtl "$OUT/patched/INITBTL.PRG" "$OUT/loader.bin" "$LOADER_BASE" \
    "$(addr "$OUT/loader.elf" vs_mod_loadSystemDat)" "$INITBTL_LOAD"
# Optional feature (Merlose options.ini): its own copy, so the kit keeps it apart
mkdir -p "$OUT/maxstats"
cp data/BATTLE/BATTLE.PRG "$OUT/maxstats/"
python3 tools/mod/build_mod.py maxstats "$OUT/maxstats/BATTLE.PRG" "$(s vs_main_getRand)" \
    "$(s _increaseStrengthRand)" "$(s _increaseIntelligenceRand)" "$(s _increaseAgilityRand)" \
    "$(s _increaseMaxHpRand)" "$(s _increaseMaxMpRand)"
python3 tools/mod/build_mod.py battle "$OUT/patched/BATTLE.PRG" "$ENTRY" "$(c vs_mod_frame)" \
    "$(c vs_mod_countTeam)" "$(c vs_mod_hud)" "$(c vs_mod_targetStatus)" "$(c vs_mod_cutsceneMode)"
python3 tools/mod/build_mod.py menu3 "$OUT/patched/MENU3.PRG" "$(c vs_mod_itemNavigation)" \
    "$(c vs_mod_equipMenu)" "$(c vs_mod_setMenuRows)" "$(c vs_mod_loadObjectData)"
python3 tools/mod/build_mod.py menu0 "$OUT/patched/MENU0.PRG" "$(c vs_mod_magicRows)" "$(c vs_mod_magicCost)"

# 5. The kit, for tools/mod/patch_image.py
python3 tools/mod/build_mod.py kit "$OUT/kit" \
    BATTLE/BATTLE.PRG "$OUT/original/BATTLE.PRG" "$OUT/patched/BATTLE.PRG" \
    BATTLE/INITBTL.PRG "$OUT/original/INITBTL.PRG" "$OUT/patched/INITBTL.PRG" \
    MENU/MENU3.PRG "$OUT/original/MENU3.PRG" "$OUT/patched/MENU3.PRG" \
    MENU/MENU0.PRG "$OUT/original/MENU0.PRG" "$OUT/patched/MENU0.PRG" \
    "$MOD_LBA" "$OUT/CALLO.BIN" "$MENU_LBA" "$OUT/CALLOMNU.BIN" \
    @max_stat_items BATTLE/BATTLE.PRG "$OUT/original/BATTLE.PRG" "$OUT/maxstats/BATTLE.PRG" \
    @choosable_bonus_wheel MENU/MENUF.PRG "$OUT/original/MENUF.PRG" "$OUT/patched/MENUF.PRG"
echo "kit: $OUT/kit"
